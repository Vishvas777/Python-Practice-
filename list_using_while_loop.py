l=[1,"harry",3.4,True,"reeva""swareena"]

i=0
while i<len(l):
    print(l[i])
    i+=1
# This is a while loop that will print elements of the list l one by one
# The loop will continue as long as the condition (i<len(l)) is true
# Since i starts at 0 and increments by 1 each iteration, it will eventually reach the length of the list, at which point the loop will stop